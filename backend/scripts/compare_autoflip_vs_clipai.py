def _serialize_reframe_segments(segments: list) -> list[dict]:
    """Emit a JSON-friendly list of dicts for ``segments.json``.

    Only the fields the translator + scoring layer care about are
    pinned; the rest are dropped so embeddings / numpy arrays never
    leak into the cache blob.

    ``motion_path`` and ``hard_constraints`` are passed through so the
    diagnostic preview renderer and the events translator can use the
    same per-frame camera path the production export pipeline uses
    (see ``render_plan_keyframes.keyframes_from_cached_render_plan``
    and the smooth interpolation in
    ``export_autoflip_compatible.build_camera_path_keypoints``).
    Each motion_path entry is normalized to a JSON-friendly list of
    ``[t, x]`` (or ``[t, x, y]`` when y is present); ``None`` is
    preserved when the source segment has no path so back-compat with
    callers that test ``"motion_path" in seg`` is maintained.
    """
    out: list[dict] = []
    for s in segments or []:
        raw_path = getattr(s, "motion_path", None)
        motion_path: Optional[list] = None
        if raw_path:
            motion_path = []
            for entry in raw_path:
                # Each entry is (t, x) or (t, x, y); preserve y if present.
                try:
                    items = [float(v) for v in entry]
                except (TypeError, ValueError):
                    continue
                if len(items) >= 2:
                    motion_path.append(items[:3])

        raw_hc = getattr(s, "hard_constraints", None)
        hard_constraints: Optional[list] = None
        if raw_hc:
            hard_constraints = []
            for hc in raw_hc:
                try:
                    items = [float(v) for v in hc]
                except (TypeError, ValueError):
                    continue
                if len(items) >= 4:
                    hard_constraints.append(items[:4])

        out.append({
            "start": float(getattr(s, "start", 0.0)),
            "end": float(getattr(s, "end", 0.0)),
            "subject_x": float(getattr(s, "subject_x", 0.0)),
            "subject_y": float(getattr(s, "subject_y", 0.0)),
            "layout": str(getattr(s, "layout", "single") or "single"),
            "active_slot": getattr(s, "active_slot", None),
            "confidence": float(getattr(s, "confidence", 0.0) or 0.0),
            "reason": str(getattr(s, "reason", "") or ""),
            "ease_in_ms": int(getattr(s, "ease_in_ms", 0) or 0),
            "strategy": str(getattr(s, "strategy", "stationary") or "stationary"),
            "content_type": str(getattr(s, "content_type", "unknown") or "unknown"),
            "motion_path": motion_path,
            "hard_constraints": hard_constraints,
        })
    return out


def _probe_source_metadata(video_path: Path) -> dict:
    """Return ``{width, height, fps, duration}`` via ffprobe. Lazy
    import + subprocess so the module stays sandbox-safe."""
    import subprocess

    cmd = [
        "ffprobe", "-v", "error", "-select_streams", "v:0",
        "-show_entries", "stream=width,height,r_frame_rate",
        "-show_entries", "format=duration",
        "-of", "json", str(video_path),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True, check=True)
    payload = json.loads(result.stdout or "{}")
    stream = (payload.get("streams") or [{}])[0]
    fmt = payload.get("format") or {}
    width = int(stream.get("width") or 0)
    height = int(stream.get("height") or 0)
    r_frame_rate = stream.get("r_frame_rate") or "30/1"
    if "/" in str(r_frame_rate):
        num, den = str(r_frame_rate).split("/")
        denf = float(den)
        fps = float(num) / denf if denf else float(num)
    else:
        fps = float(r_frame_rate)
    duration = float(fmt.get("duration") or 0.0)
    return {
        "width": width, "height": height, "fps": fps, "duration": duration,
    }


def _compute_saliency_peaks_per_second(
    video_path: Path,
    audio_path: Optional[Path],
    duration: float,
    *,
    slug: str,
) -> list:
    """Layer 1: produce per-second saliency peaks for ``video_path``.

    Sampling: one frame per second via ffmpeg, fed into
    :class:`AvSaliency`. Audio energy at 1 Hz comes from
    :func:`av_saliency.audio_energy_per_second`.

    Returns ``[]`` on any failure path — missing ffmpeg, ImportError on
    ``tasednet``, no GPU, OOM. The bench's saliency-in-crop metric and
    the Layer 1 critic both treat an empty list as "not measured" and
    silently skip the check, so a homelab without TASED-Net installed
    still produces a fully-valid v6 cache.

    Output schema matches ``saliency_in_crop_fraction``:
    ``[[ (x_pct, y_pct, score), ... ]_for_second_0, ...]``.
    """
    if not _saliency_layer_enabled():
        return []
    try:
        from backend.services.av_saliency import (
            AvSaliency, audio_energy_per_second,
        )
    except Exception as exc:
        logger.warning(
            "[%s] saliency layer: import failed (%s) — empty peaks",
            slug, exc,
        )
        return []

    n_seconds = max(1, int(round(duration)))

    # Audio energy (1 Hz). Tolerates missing wav by passing zeros.
    audio_energy_1hz: Any = None
    try:
        import numpy as _np  # noqa: F401  — used inside the try
        if audio_path and Path(audio_path).is_file():
            try:
                import wave
                with wave.open(str(audio_path), "rb") as wf:
                    sr = wf.getframerate()
                    nchan = wf.getnchannels()
                    nframes = wf.getnframes()
                    raw = wf.readframes(nframes)
                import numpy as np
                samples = np.frombuffer(raw, dtype=np.int16)
                if nchan > 1:
                    samples = samples.reshape(-1, nchan).mean(axis=1)
                samples = samples.astype(np.float32) / 32768.0
                audio_energy_1hz = audio_energy_per_second(samples, sr)
            except Exception as exc:
                logger.info(
                    "[%s] saliency layer: audio energy failed (%s) — using zeros",
                    slug, exc,
                )
        if audio_energy_1hz is None:
            import numpy as np
            audio_energy_1hz = np.zeros(n_seconds, dtype=np.float32)
    except Exception as exc:
        logger.info(
            "[%s] saliency layer: numpy unavailable (%s) — empty peaks",
            slug, exc,
        )
        return []

    # Frame sampling at 1 fps via ffmpeg. Output goes to a temp dir so
    # we don't pollute the cache.
    import shutil as _shutil
    import subprocess
    import tempfile
    if not _shutil.which("ffmpeg"):
        logger.info(
            "[%s] saliency layer: ffmpeg not available — empty peaks", slug,
        )
        return []
    tmp = Path(tempfile.mkdtemp(prefix="clipai_saliency_frames_"))
    try:
        cmd = [
            "ffmpeg", "-y", "-loglevel", "error",
            "-i", str(video_path),
            "-vf", "fps=1,scale=256:144",
            str(tmp / "f%04d.png"),
        ]
        try:
            subprocess.run(cmd, check=True, timeout=300, capture_output=True)
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
            logger.info(
                "[%s] saliency layer: ffmpeg sampling failed (%s) — empty peaks",
                slug, exc,
            )
            return []

        png_paths = sorted(tmp.glob("f*.png"))
        if not png_paths:
            return []
        try:
            import numpy as np
            try:
                import cv2  # type: ignore
            except Exception as exc:
                logger.info(
                    "[%s] saliency layer: cv2 unavailable (%s) — empty peaks",
                    slug, exc,
                )
                return []
            frames = np.stack([
                cv2.cvtColor(cv2.imread(str(p)), cv2.COLOR_BGR2RGB)
                for p in png_paths
            ]).astype(np.uint8)
        except Exception as exc:
            logger.info(
                "[%s] saliency layer: frame load failed (%s) — empty peaks",
                slug, exc,
            )
            return []

        # Determine device — fall back to CPU when GPU not visible.
        from backend.services.av_saliency import _is_gpu_visible
        device = "cuda" if _is_gpu_visible() else "cpu"
        backend_name = "unknown"
        try:
            avs = AvSaliency(device=device)
            backend_name = avs.backend_name
            result = avs.predict(frames, audio_energy_1hz)
        except Exception as exc:
            logger.warning(
                "[%s] saliency layer: AvSaliency.predict failed (%s) — empty peaks",
                slug, exc,
            )
            return []

        # Free the model + GPU memory before the LP solver runs.
        try:
            del avs
            if device == "cuda":
                import torch  # type: ignore
                torch.cuda.empty_cache()
        except Exception:
            pass

        # Stash the chosen backend on the function so the caller can
        # surface it in result.critic.saliency.backend without
        # threading another return value through every call site.
        _compute_saliency_peaks_per_second.last_backend = backend_name  # type: ignore[attr-defined]

        # Serialize peaks: each second is a list of [x_pct, y_pct, score].
        out: list = []
        for sec_peaks in result.peaks:
            out.append([
                [float(x), float(y), float(s)] for (x, y, s) in sec_peaks
            ])
        return out
    finally:
        try:
            _shutil.rmtree(tmp, ignore_errors=True)
        except Exception:
            pass


