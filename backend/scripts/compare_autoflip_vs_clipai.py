def _build_anime_features_seq(dense_faces: list) -> list:
    """Build ``AnimeFrameFeatures`` stream from dense face results.
    Mirrors the pipeline's v4 path (face pick + frame-to-frame
    motion delta), minus the OpenCV contrast / saturation cascade.
    """
    from backend.services.anime_anchor import AnimeFrameFeatures

    out: list = []
    prev_x: Optional[float] = None
    prev_y: Optional[float] = None
    for df in dense_faces or []:
        best = None
        best_score = -1.0
        for f in getattr(df, "faces", None) or []:
            conf = float(getattr(f, "confidence", 0.0) or 0.0)
            if conf > best_score:
                best_score = conf
                best = f
        face_x = float(getattr(best, "nose_x", 50.0)) if best else 50.0
        face_y = float(getattr(best, "nose_y", 50.0)) if best else 50.0
        face_score = (
            max(0.0, min(1.0, best_score)) if best is not None else 0.0
        )
        if prev_x is None:
            motion = 0.0
        else:
            motion = min(1.0, (abs(face_x - prev_x) + abs(face_y - prev_y)) / 20.0)
        prev_x, prev_y = face_x, face_y
        out.append(AnimeFrameFeatures(
            timestamp=float(getattr(df, "timestamp", 0.0)),
            face_x_pct=face_x,
            face_y_pct=face_y,
            face_score=face_score,
            motion_energy=motion,
        ))
    return out


def _assert_content_type_routes_to_target(
    clip: dict, content_profile, slug: str,
) -> None:
    """Run ``classify_clip`` and log a warning (not an abort) if the
    classifier's output diverges from the manifest's editorial
    ``target_clipcontenttype``. The divergence itself is a signal
    worth capturing in the harness output."""
    target = str(clip.get("target_clipcontenttype") or "").strip()
    if not target:
        return
    try:
        from backend.services.content_classifier import classify_clip
        got = classify_clip(content_profile=content_profile)
        got_val = getattr(got, "value", str(got))
    except Exception as exc:  # pragma: no cover - defensive
        logger.warning(
            "[%s] classify_clip raised %s — skipping divergence check",
            slug, type(exc).__name__,
        )
        return
    if got_val != target:
        logger.warning(
            "[%s] classify_clip divergence: manifest target=%s "
            "classifier=%s (profile content_type=%s "
            "is_multi_speaker_panel=%s is_animated=%s)",
            slug, target, got_val,
            getattr(content_profile, "content_type", None),
            getattr(content_profile, "is_multi_speaker_panel", None),
            getattr(content_profile, "is_animated", None),
        )


def _extract_and_cache(
    clip: dict,
    video_path: Path,
    clip_cache: Path,
    *,
    cache_embeddings: bool,
) -> dict:
    """Full extraction + segmenter run + cache population.

    Wipes the destination directory before rebuilding so partial
    caches can't leak across runs. Returns the in-memory extraction
    payload so the caller doesn't need a second round trip to disk.
    """
    # Wipe and recreate so partial caches can't leak.
    if clip_cache.exists():
        shutil.rmtree(clip_cache)
    clip_cache.mkdir(parents=True, exist_ok=True)

    slug = str(clip.get("slug") or video_path.stem)
    sha = _sha256_file(video_path)

    # Lazy imports so sandbox stays clean.
    from backend.services.shot_detector import detect_shots
    from backend.services.face_detector import detect_faces_dense
    from backend.services.face_registry import (
        build_face_registry_with_embeddings,
        FaceRegistry,
    )
    from backend.services.content_classifier import classify_content
    from backend.services.active_speaker import (
        build_active_speaker_timeline,
        build_active_speaker_timeline_v2,
    )
    from backend.services.reframe_segmenter import build_reframe_segments
    from backend.services.anime_anchor import (
        USE_ANIME_ANCHOR,
        score_anime_sequence,
    )

    # ── Source metadata via ffprobe ──
    source_meta = _probe_source_metadata(video_path)
    duration = float(source_meta["duration"])
    width = int(source_meta["width"])
    height = int(source_meta["height"])
    fps = float(source_meta["fps"])
    metadata = {
        "slug": slug,
        "sha256": sha,
        "width": width,
        "height": height,
        "fps": fps,
        "duration": duration,
    }
    (clip_cache / "metadata.json").write_text(json.dumps(metadata, indent=2))

    # ── Shots ──
    shots = detect_shots(str(video_path), video_duration=duration) or []
    (clip_cache / "shots.json").write_text(
        json.dumps(_serialize_shots(shots), indent=2),
    )
    shot_cuts = [float(getattr(s, "start", 0.0)) for s in shots]

    # ── Dense faces ──
    dense_faces = detect_faces_dense(
        str(video_path),
        start=0.0,
        end=duration,
        sample_rate=0.5,
        min_confidence=0.4,
        extract_embeddings=True,
    ) or []
    (clip_cache / "dense_faces.json").write_text(
        json.dumps(
            _serialize_dense_faces(
                dense_faces, include_embeddings=cache_embeddings,
            ),
            indent=2,
        ),
    )

    # ── Face registry (embedding-based when we have dense data) ──
    # XC.1: burn-in filter so B-roll / title-card frames don't
    # influence slot discovery. The full ``dense_faces`` list still
    # flows downstream — only registry-input is filtered.
    if dense_faces:
        from backend.services.face_registry import (
            apply_face_registry_burn_in,
        )
        registry_input = apply_face_registry_burn_in(dense_faces)
        face_registry = build_face_registry_with_embeddings(
            registry_input, min_appearances=3, cosine_threshold=0.25,
        )
    else:
        face_registry = FaceRegistry()
    (clip_cache / "face_registry.json").write_text(
        json.dumps(_serialize_face_registry(face_registry), indent=2),
    )

    # ── Audio + transcript ──
    # The audio WAV lives alongside the extraction artifacts so the
    # v2 active-speaker path can reuse it without re-extracting.
    transcript: list = []
    audio_path: Optional[Path] = None
    try:
        audio_path = _extract_audio_wav(video_path, clip_cache)
        transcript = _transcribe_sync(audio_path) or []
    except Exception as exc:
        logger.warning(
            "[%s] audio extraction / transcription failed (non-fatal): %s",
            slug, exc,
        )
        transcript = []
    (clip_cache / "transcript.json").write_text(
        json.dumps(_serialize_transcript(transcript), indent=2),
    )

    # ── Active speaker events ──
    # Task C: mirror the production pipeline's v3 → v2 → v1 fallback
    # chain (pipeline.py around line 4015) so the bench's extracted
    # cache holds the same timeline shape production produces. Without
    # this, the Settings → Validate Test panel showed v2 numbers while
    # production was running v3, and the operator couldn't reason
    # about regressions in either direction.
    speaker_events: list = []
    asd_scores_for_cache: list = []
    asd_backend = _active_asd_backend()
    has_face_data = bool(
        face_registry
        and getattr(face_registry, "multi_speaker", False)
        and transcript
        and dense_faces
    )
    try:
        if asd_backend == "light_asd" and has_face_data:
            try:
                from backend.services.light_asd import score_faces_for_clip
                from backend.services.active_speaker import (
                    build_active_speaker_timeline_v3,
                )
                asd_scores_for_cache = score_faces_for_clip(
                    video_path=str(video_path),
                    face_results=dense_faces,
                    audio_wav_path=str(audio_path) if audio_path else None,
                ) or []
                if asd_scores_for_cache:
                    speaker_events = build_active_speaker_timeline_v3(
                        dense_faces, transcript,
                        asd_scores=asd_scores_for_cache,
                        face_registry=face_registry,
                        window_seconds=0.5,
                        shot_cuts=shot_cuts,
                        audio_path=str(audio_path) if audio_path else None,
                    ) or []
            except Exception as exc:
                logger.warning(
                    "[%s] Light-ASD path failed in bench (non-fatal): %s; "
                    "falling back to v2 heuristic", slug, exc,
                )

        # v2 fallback when v3 is off, the model failed, or scores
        # were empty.
        if not speaker_events and has_face_data:
            speaker_events = build_active_speaker_timeline_v2(
                dense_faces, transcript, face_registry,
                window_seconds=0.5,
                shot_cuts=shot_cuts,
                audio_path=str(audio_path) if audio_path else None,
            ) or []
        # v1 fallback when dense face data isn't available.
        elif (
            not speaker_events
            and face_registry
            and getattr(face_registry, "multi_speaker", False)
            and transcript
        ):
            speaker_events = build_active_speaker_timeline(
                dense_faces, transcript, face_registry,
                window_seconds=2.0,
                shot_cuts=shot_cuts,
                audio_path=str(audio_path) if audio_path else None,
            ) or []
    except Exception as exc:
        logger.warning(
            "[%s] active speaker timeline failed (non-fatal): %s",
            slug, exc,
        )
        speaker_events = []
    (clip_cache / "speaker_events.json").write_text(
        json.dumps(_serialize_speaker_events(speaker_events), indent=2),
    )

    # Task C: persist the per-frame ASD scores so re-runs can reuse
    # them without paying the inference cost twice. Only written when
    # the Light-ASD backend produced scores; the cache validity check
    # only requires this file when CLIPAI_ASD_BACKEND=light_asd, so
    # heuristic-mode caches don't need the file at all.
    if asd_backend == "light_asd":
        (clip_cache / "asd_scores.json").write_text(
            json.dumps([
                {
                    "timestamp": float(getattr(s, "timestamp", 0.0)),
                    "face_idx": int(getattr(s, "face_idx", -1) or -1),
                    "p_speaking": float(getattr(s, "p_speaking", 0.0)),
                }
                for s in asd_scores_for_cache
            ], indent=2),
        )

    # ── Layer 1: per-second saliency peaks (TASED-Net) ──
    # Runs AFTER Whisper / Light-ASD have unloaded so the 4 GB
    # GTX 1650 isn't holding three models at once. Always-write
    # behavior — failure paths produce an empty list rather than
    # crashing the cache. ``CLIPAI_SALIENCY_LAYER=0`` skips the run
    # entirely and writes ``[]`` (also the v6-required schema).
    saliency_peaks: list = []
    saliency_backend: str = "disabled"
    if _saliency_layer_enabled():
        try:
            saliency_peaks = _compute_saliency_peaks_per_second(
                video_path, audio_path, duration, slug=slug,
            )
            saliency_backend = getattr(
                _compute_saliency_peaks_per_second, "last_backend", "unknown",
            ) if saliency_peaks else "failed"
        except Exception as exc:
            logger.warning(
                "[%s] saliency layer raised unexpectedly (%s) — empty peaks",
                slug, exc,
            )
            saliency_peaks = []
            saliency_backend = "failed"
    (clip_cache / "saliency_peaks_per_second.json").write_text(
        json.dumps(saliency_peaks),
    )
    (clip_cache / "saliency_meta.json").write_text(
        json.dumps({"backend": saliency_backend}),
    )

    # ── Content profile ──
    classifier_meta = _classifier_metadata_from_clip(clip)
    content_profile = None
    try:
        content_profile = classify_content(
            shot_cuts=shot_cuts,
            face_registry=face_registry,
            dense_faces=dense_faces,
            scenes=[],
            video_duration=duration,
            metadata=classifier_meta,
            transcript_segments=transcript,
        )
    except Exception as exc:
        logger.warning(
            "[%s] classify_content failed (non-fatal): %s", slug, exc,
        )
    (clip_cache / "content_profile.json").write_text(
        json.dumps(_serialize_content_profile(content_profile), indent=2),
    )

    _assert_content_type_routes_to_target(clip, content_profile, slug)

    # ── Anime anchors (gated) ──
    anime_anchors: list = []
    if (
        content_profile is not None
        and getattr(content_profile, "is_animated", False)
        and USE_ANIME_ANCHOR
    ):
        try:
            features_seq = _build_anime_features_seq(dense_faces)
            anime_anchors = list(score_anime_sequence(
                features_seq,
                anime_subtype=getattr(content_profile, "anime_subtype", None),
            ))
        except Exception as exc:
            logger.warning(
                "[%s] anime anchor extraction failed (non-fatal): %s",
                slug, exc,
            )
            anime_anchors = []
    (clip_cache / "anime_anchors.json").write_text(
        json.dumps(_serialize_anime_anchors(anime_anchors), indent=2),
    )

    # ── Reframe segments ──
    segments = build_reframe_segments(
        shot_cuts=shot_cuts,
        face_registry=face_registry,
        active_speaker_events=speaker_events,
        dense_faces=dense_faces,
        transcript_segments=transcript,
        speaker_to_slot={},
        video_duration=duration,
        source_width=width or 1920,
        source_height=height or 1080,
        job_id=slug,
        content_profile=content_profile,
        persistent_regions=None,
        pacing_estimator=None,
        interpolated_timeline=None,
        frame_saliency=None,
        music_beat_grid=None,
        anime_anchors=anime_anchors or None,
        debug_out={},
    ) or []
    segments_serialized = _serialize_reframe_segments(segments)
    (clip_cache / "segments.json").write_text(
        json.dumps(segments_serialized, indent=2),
    )

    # Stamp the cache version LAST so a crash partway through leaves
    # the directory invalid (required-file check fails).
    (clip_cache / "cache_version.txt").write_text(
        str(EXTRACTION_CACHE_VERSION),
    )

    return {
        "metadata": metadata,
        "segments": segments_serialized,
        "saliency_peaks_per_second": saliency_peaks,
        "saliency_backend": saliency_backend,
    }


def _load_cached_extraction(clip_cache: Path) -> dict:
    metadata = json.loads((clip_cache / "metadata.json").read_text())
    segments = json.loads((clip_cache / "segments.json").read_text())
    payload: dict[str, Any] = {"metadata": metadata, "segments": segments}
    # Task 2 per-frame data — optional. When the cache predates these
    # fields the keys stay missing; ``extract_per_frame_data_from_payload``
    # returns None for each so the metrics report "not measured" instead
    # of "perfect."
    for fname, key in (
        ("face_bboxes_per_frame.json", "face_bboxes_per_frame"),
        ("saliency_peaks_per_second.json", "saliency_peaks_per_second"),
        ("text_regions_per_frame.json", "text_regions_per_frame"),
        ("identity_timeline.json", "identity_timeline"),
    ):
        path = clip_cache / fname
        if path.is_file():
            try:
                payload[key] = json.loads(path.read_text())
            except (OSError, json.JSONDecodeError) as exc:
                logger.warning(
                    "extraction cache: failed to load %s: %s", fname, exc,
                )
    # Layer 1 backend metadata (which adapter actually ran). Optional —
    # caches written before saliency_meta.json existed return None.
    meta_path = clip_cache / "saliency_meta.json"
    if meta_path.is_file():
        try:
            payload["saliency_backend"] = json.loads(
                meta_path.read_text()
            ).get("backend")
        except (OSError, json.JSONDecodeError):
            pass
    return payload


def _count_saliency_flagged_windows(
    events: list, saliency_peaks_per_second: Optional[list],
    *, crop_width_pct: float = 56.25,
) -> int:
    """Count seconds where every top-K saliency peak lies outside the
    crop, mirroring the ``saliency_excluded`` flag in
    ``reframe_critic._saliency_in_crop_at`` (Layer 1).

    Returns 0 when no peaks data is available — "not measured" rather
    than "everything is fine."
    """
    if not events or not saliency_peaks_per_second:
        return 0
    half = crop_width_pct / 2.0
    # Bucket events by integer second; use the median crop center
    # within each second to avoid sub-second jitter.
    seconds: dict[int, list[float]] = {}
    for e in events:
        try:
            t = float(e.get("t", 0.0))
            cx = float(e.get("crop_cx", 0.5)) * 100.0
        except (TypeError, ValueError):
            continue
        seconds.setdefault(int(t), []).append(cx)
    flagged = 0
    for sec_idx, peaks in enumerate(saliency_peaks_per_second):
        if not peaks:
            continue
        cxs = seconds.get(sec_idx)
        if not cxs:
            continue
        cxs_sorted = sorted(cxs)
        cx = cxs_sorted[len(cxs_sorted) // 2]  # median
        any_in = False
        for peak in peaks:
            try:
                px = float(peak[0])
            except (TypeError, ValueError, IndexError):
                continue
            if cx - half <= px <= cx + half:
                any_in = True
                break
        if not any_in:
            flagged += 1
    return flagged


def extract_per_frame_data_from_payload(payload: dict) -> dict[str, Optional[list]]:
    """Return the four optional per-frame structures Task 2 metrics need.

    Older extraction caches don't have these — for those, every value
    is ``None``. The bench treats ``None`` as "not measured" which keeps
    missing data from being silently scored as a perfect zero.
    """
    return {
        "face_bboxes_per_frame": payload.get("face_bboxes_per_frame"),
        "saliency_peaks_per_second": payload.get("saliency_peaks_per_second"),
        "text_regions_per_frame": payload.get("text_regions_per_frame"),
        "identity_timeline": payload.get("identity_timeline"),
    }


def run_clipai_on_clip(
    clip: dict,
    video_path: Optional[Path],
    *,
    dry_run: bool = False,
    cache_dir: Optional[Path] = None,
    cache_embeddings: bool = False,
    force_reextract: bool = False,
    extras_out: Optional[dict] = None,
) -> Optional[list[dict]]:
    """Produce a ClipAI timeline event list for a clip.

    Two operating modes:

    1. ``dry_run=True`` or ``video_path is None`` — returns the
       legacy synthetic one-frame-per-frame timeline so the
       ``--dry-run`` iteration path (scoring-layer-only work)
       stays fast and sandbox-safe. This is the same shape the
       existing harness tests pin.

    2. Real invocation — resolves the extraction cache under
       ``cache_dir`` (or ``$CLIPAI_REAL_CONTENT_CACHE/extractions``),
       runs the full extraction stack (shots → dense faces →
       registry → transcript → active speaker → content profile →
       anime anchors → reframe segments) when the cache is cold,
       and translates the segment list via
       ``export_autoflip_compatible.reframe_segments_to_events``.

    Returns ``None`` when the video path is supplied but does not
    exist on disk — the harness reports that row as
    ``clipai_skipped``.
    """
    # ── Synthetic / dry-run path ──
    if dry_run or video_path is None:
        return _synthetic_events_for_clip(clip)

    slug = str(clip.get("slug") or "")

    # ── Missing file → skipped row ──
    video_path = Path(video_path)
    if not video_path.is_file():
        logger.warning(
            "[%s] run_clipai_on_clip: video not found at %s — returning None",
            slug, video_path,
        )
        return None

    # ── Resolve cache dir ──
    resolved_cache_dir = (
        Path(cache_dir) if cache_dir is not None
        else _default_extraction_cache_dir()
    )

    try:
        sha = _sha256_file(video_path)
    except OSError as exc:
        logger.warning(
            "[%s] failed to hash %s: %s — returning None",
            slug, video_path, exc,
        )
        return None

    clip_cache = resolved_cache_dir / sha

    if not force_reextract and _cache_is_valid(clip_cache):
        logger.info(
            "[%s] extraction cache HIT at %s", slug, clip_cache,
        )
        payload = _load_cached_extraction(clip_cache)
    else:
        logger.info(
            "[%s] extraction cache MISS at %s — running full extraction",
            slug, clip_cache,
        )
        try:
            payload = _extract_and_cache(
                clip, video_path, clip_cache,
                cache_embeddings=cache_embeddings,
            )
        except Exception as exc:
            logger.warning(
                "[%s] extraction failed: %s — returning None",
                slug, exc,
            )
            return None

    metadata = payload.get("metadata") or {}
    segments = payload.get("segments") or []
    src_w = int(metadata.get("width") or 1920)
    src_h = int(metadata.get("height") or 1080)
    fps = float(metadata.get("fps") or 30.0)

    # Lazy import of the translator so the dry-run path stays
    # sandbox-safe (the translator itself is pure, but the import
    # sits next to the ffprobe helper we DON'T want to drag along).
    from backend.scripts.export_autoflip_compatible import (
        reframe_segments_to_events,
    )
    events = reframe_segments_to_events(
        segments, src_w, src_h, fps, aspect_ratio="9:16",
    )
    if extras_out is not None:
        extras_out.update(extract_per_frame_data_from_payload(payload))
        # ``saliency_backend`` is consumed by the result.critic block
        # in main(), not by ``score_timeline`` (which would reject the
        # unknown kwarg). Stash it under a leading-underscore key the
        # caller pops before splatting extras into score_timeline.
        backend = payload.get("saliency_backend")
        if backend is not None:
            extras_out["_saliency_backend"] = backend
    return events


def load_autoflip_timeline(
    clip: dict, autoflip_dir: Path,
    *,
    return_tool: bool = False,
) -> Optional[list[dict]] | tuple[Optional[list[dict]], Optional[str]]:
    """Load the AutoFlip-shape event list for one clip.

    When ``return_tool`` is True, returns ``(events, tool_label)``
    where ``tool_label`` is the JSON's ``tool`` field — typically
    one of ``autoflip_real``, ``autoflip_prebuilt``, or
    ``naive_baseline``. The legacy single-return shape is preserved
    (``return_tool`` defaults to False) so older callers keep working.
    """
    slug = clip["slug"]
    path = autoflip_dir / f"{slug}.json"
    if not path.is_file():
        if return_tool:
            return None, None
        return None
    try:
        payload = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as e:
        logger.warning("[%s] AutoFlip JSON load failed: %s", slug, e)
        if return_tool:
            return None, None
        return None
    events = payload.get("events") or []
    tool = payload.get("tool")
    if not events:
        if return_tool:
            return None, tool
        return None
    if return_tool:
        return events, tool
    return events


def load_ground_truth_timeline(
    clip: dict, ground_truth_dir: Path,
) -> Optional[list[dict]]:
    slug = clip["slug"]
    path = ground_truth_dir / f"{slug}.json"
    if not path.is_file():
        return None
    try:
        payload = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None
    return payload.get("events") or None


