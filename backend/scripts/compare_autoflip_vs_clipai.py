_GROUP_ORDER = [
    ("panels", {"multi_speaker_panel"}),
    ("anime", {"animation", "animation_dialogue"}),
    ("sports", {"sports", "sports_basketball", "sports_racing"}),
    ("music", {"music_video"}),
]


def _group_for(clip: dict) -> str:
    ct = clip.get("target_clipcontenttype") or ""
    for group_name, cts in _GROUP_ORDER:
        if ct in cts:
            return group_name
    return "other"


def _fmt(v: Any, digits: int = 2, missing: str = "—") -> str:
    if v is None:
        return missing
    if isinstance(v, (int, float)):
        return f"{v:.{digits}f}"
    return str(v)


def render_markdown(
    results: list[ClipResult],
    *,
    autoflip_outputs_dir: Path,
    clipai_invocation: str,
) -> str:
    """Emit the per-group markdown rollup."""
    by_group: dict[str, list[ClipResult]] = {}
    for r in results:
        by_group.setdefault(
            _group_for({
                "target_clipcontenttype": r.target_clipcontenttype,
                "subtype": r.subtype,
            }),
            [],
        ).append(r)

    out: list[str] = []
    out.append("# Week 3 — Real-content comparison results\n")
    out.append(
        "Generated by "
        "`backend/scripts/compare_autoflip_vs_clipai.py`. Each row is "
        "one (clip, tool) pair. Verdict uses the per-content-type "
        "target zone from `TARGET_ZONES` when no human ground-truth "
        "sidecar is available.\n"
    )
    # Task 5A — surface which tool produced each AutoFlip cell so a
    # SOTA claim isn't accidentally made against the naive strawman.
    af_tools = [r.autoflip_tool for r in results if r.autoflip_tool]
    real_count = sum(1 for t in af_tools if t in ("autoflip_real", "autoflip_prebuilt"))
    naive_count = sum(1 for t in af_tools if t == "naive_baseline")
    out.append(
        f"- Clips scored: **{len(results)}**\n"
        f"- AutoFlip outputs dir: `{autoflip_outputs_dir}`\n"
        f"- AutoFlip references: {real_count} real, {naive_count} naive_baseline\n"
        f"- ClipAI invocation mode: `{clipai_invocation}`\n"
    )
    if naive_count > 0 and real_count == 0:
        out.append(
            "\n> **Warning** — every AutoFlip column on this run was "
            "produced by the naive center-crop baseline, not real "
            "MediaPipe AutoFlip. Run `make autoflip-references` to "
            "regenerate against the real comparator before making any "
            "SOTA claims.\n"
        )

    for group, cts in _GROUP_ORDER:
        group_results = by_group.get(group) or []
        if not group_results:
            continue
        out.append(f"\n## {group.title()}\n")
        out.append(
            "| Clip | Tool | median | p25 | p75 | under_1s | over_8s | "
            "max_accel | max_jerk | verdict |\n"
        )
        out.append(
            "|---|---|---|---|---|---|---|---|---|---|\n"
        )
        # Per-row autoflip label depends on the source JSON's tool
        # field so the markdown column reads "autoflip (real)" vs
        # "autoflip (naive)" distinctly.
        _AUTOFLIP_LABEL_MAP = {
            "autoflip_real": "autoflip (real)",
            "autoflip_prebuilt": "autoflip (prebuilt)",
            "naive_baseline": "autoflip (naive)",
        }
        for r in group_results:
            af_label = _AUTOFLIP_LABEL_MAP.get(
                r.autoflip_tool or "", "autoflip",
            )
            for tool, label in (
                ("autoflip", af_label),
                ("clipai", "**clipai**"),
                ("ground_truth", "ground_truth"),
            ):
                m = getattr(r, tool)
                if m is None:
                    out.append(
                        f"| `{r.slug}` | {label} | "
                        f"— | — | — | — | — | — | — | SKIPPED |\n"
                    )
                    continue
                out.append(
                    f"| `{r.slug}` | {label} | "
                    f"{_fmt(m.get('median_hold_sec'))} | "
                    f"{_fmt(m.get('p25'))} | "
                    f"{_fmt(m.get('p75'))} | "
                    f"{_fmt(m.get('segments_under_1s_rate'), 2)} | "
                    f"{_fmt(m.get('segments_over_8s_rate'), 2)} | "
                    f"{_fmt(m.get('max_acceleration'))} | "
                    f"{_fmt(m.get('max_jerk'))} | "
                    f"{r.verdicts.get(tool, 'UNKNOWN')} |\n"
                )
            if r.notes:
                out.append(
                    f"| | _{' · '.join(r.notes)}_ | | | | | | | | |\n"
                )
    return "".join(out)


# ─────────────────── Main loop ───────────────────


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest", default="tests/real_content/manifest.json",
    )
    parser.add_argument(
        "--autoflip-outputs",
        default="tests/autoflip_reference_outputs",
    )
    parser.add_argument(
        "--ground-truth-dir",
        default="tests/real_content/ground_truth",
    )
    parser.add_argument(
        "--output",
        default="docs/week3_real_content_results.md",
    )
    parser.add_argument(
        "--json-out",
        default="/tmp/week3_results.json",
    )
    parser.add_argument(
        "--filter", default="*",
        help="Only score clips whose slug matches the glob",
    )
    parser.add_argument(
        "--filter-slugs", default=None,
        help=(
            "Comma-separated list of exact slugs to score. Applied "
            "after --filter. When unset (default) every clip that "
            "matches --filter runs."
        ),
    )
    parser.add_argument(
        "--clipai-only", action="store_true",
        help="Skip AutoFlip load (mark every clip's autoflip as SKIPPED)",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Emit stubbed ClipAI timelines without invoking the pipeline",
    )
    parser.add_argument(
        "--real-content-dir", default=None,
        help=(
            "Directory containing the resolved clip videos. Defaults "
            "to $CLIPAI_REAL_CONTENT_CACHE (/var/cache/clipai/real_content "
            "if unset). Each clip is looked up as <dir>/<slug>.<ext>."
        ),
    )
    parser.add_argument(
        "--extraction-cache-dir", default=None,
        help=(
            "Directory for the per-clip extraction cache "
            "($CLIPAI_REAL_CONTENT_CACHE/extractions by default)."
        ),
    )
    parser.add_argument(
        "--cache-embeddings", action="store_true",
        help="Persist identity embeddings in dense_faces.json (large).",
    )
    parser.add_argument(
        "--force-reextract", action="store_true",
        help="Ignore the extraction cache and rebuild every clip.",
    )
    parser.add_argument(
        "--quiet", action="store_true",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.WARNING if args.quiet else logging.INFO,
        format="%(levelname)s %(name)s: %(message)s",
    )

    manifest_path = Path(args.manifest)
    if not manifest_path.is_file():
        logger.error("manifest not found at %s", manifest_path)
        return 2
    manifest = json.loads(manifest_path.read_text())

    autoflip_dir = Path(args.autoflip_outputs)
    gt_dir = Path(args.ground_truth_dir)

    # ── Resolve real-content + extraction cache roots ──
    real_content_dir = (
        Path(args.real_content_dir) if args.real_content_dir
        else Path(os.environ.get(
            "CLIPAI_REAL_CONTENT_CACHE", "/var/cache/clipai/real_content",
        ))
    )
    extraction_cache_dir = (
        Path(args.extraction_cache_dir) if args.extraction_cache_dir
        else _default_extraction_cache_dir()
    )

    results: list[ClipResult] = []
    filter_glob = args.filter
    slug_whitelist: Optional[set[str]] = None
    if args.filter_slugs:
        slug_whitelist = {
            s.strip() for s in args.filter_slugs.split(",") if s.strip()
        }

    for clip in manifest.get("clips", []):
        slug = clip.get("slug") or ""
        if not fnmatch.fnmatch(slug, filter_glob):
            continue
        if slug_whitelist is not None and slug not in slug_whitelist:
            continue

        result = ClipResult(
            slug=slug,
            content_type=clip.get("content_type") or "",
            target_clipcontenttype=clip.get("target_clipcontenttype") or "",
            subtype=clip.get("subtype"),
        )

        # AutoFlip timeline
        if args.clipai_only:
            result.notes.append("autoflip skipped (--clipai-only)")
        else:
            af_events, af_tool = load_autoflip_timeline(
                clip, autoflip_dir, return_tool=True,
            )
            result.autoflip_tool = af_tool
            if af_events is None:
                result.notes.append(
                    f"no AutoFlip cache at {autoflip_dir}/{slug}.json"
                )
            else:
                result.autoflip = score_timeline(af_events)
                if af_tool == "naive_baseline":
                    result.notes.append(
                        "autoflip column is naive_baseline (Path B "
                        "fallback) — re-run 'make autoflip-references' "
                        "for real comparison"
                    )

        # ClipAI timeline
        # Resolve the on-disk video path from the real-content dir,
        # using the manifest's slug + ext. In dry-run mode we pass
        # None so the synthetic path fires regardless.
        if args.dry_run:
            _video_path = None
        else:
            _ext = str(clip.get("ext") or "mp4")
            _candidate = real_content_dir / f"{slug}.{_ext}"
            _video_path = _candidate if _candidate.is_file() else None
            if _video_path is None:
                result.notes.append(
                    f"no clip at {_candidate}"
                )
        ca_extras: dict = {}
        ca_events = run_clipai_on_clip(
            clip,
            video_path=_video_path,
            dry_run=args.dry_run,
            cache_dir=extraction_cache_dir,
            cache_embeddings=args.cache_embeddings,
            force_reextract=args.force_reextract,
            extras_out=ca_extras,
        )
        if ca_events is None:
            if args.dry_run:
                result.notes.append("clipai pipeline invocation not wired")
            else:
                result.notes.append("clipai_skipped")
        else:
            # Layer 1: pop the out-of-band saliency backend before
            # splatting extras into score_timeline (which only accepts
            # the documented per-frame kwargs).
            sal_backend = ca_extras.pop("_saliency_backend", None)
            result.clipai = score_timeline(ca_events, **ca_extras)
            # Layer 1: surface saliency-in-crop into the critic block
            # so the UI / JSON consumer can render the Critic Engine
            # rows. We compute ``windows_flagged`` here from the same
            # peaks + crop centers the in-crop fraction uses, so the
            # bench reports a real number even though it doesn't run
            # ``auto_repair_plan`` directly. ``windows_fixed`` stays
            # None until the bench drives the bridge end-to-end —
            # production exports already get the fixes via
            # ``human_reframe_bridge.maybe_override_render_plan``.
            sal_peaks = ca_extras.get("saliency_peaks_per_second")
            sal_in_crop = (
                result.clipai.get("saliency_in_crop_fraction")
                if isinstance(result.clipai, dict) else None
            )
            if (
                sal_peaks is not None
                or sal_in_crop is not None
                or sal_backend
            ):
                # Count seconds where every top-K peak fell outside the
                # crop window — these are the "flagged" windows the
                # critic would auto-widen during the production export.
                windows_flagged = _count_saliency_flagged_windows(
                    ca_events, sal_peaks,
                )
                result.critic = {
                    "saliency": {
                        "in_crop_fraction": sal_in_crop,
                        # Alias used by the UI's Critic engine row —
                        # same value, more readable key.
                        "in_crop_mean": sal_in_crop,
                        "n_seconds_with_peaks": (
                            sum(1 for s in (sal_peaks or []) if s)
                        ),
                        "windows_flagged": windows_flagged,
                        "windows_fixed": None,
                        "backend": sal_backend,
                    },
                }

        # Optional human ground truth
        gt_events = load_ground_truth_timeline(clip, gt_dir)
        if gt_events:
            result.ground_truth = score_timeline(gt_events)

        # Verdicts
        zone = target_zone_for(clip)
        for tool in ("autoflip", "clipai", "ground_truth"):
            m = getattr(result, tool)
            if m is None:
                continue
            result.verdicts[tool] = verdict_for(m, zone)

        results.append(result)

    # Emit markdown
    md_body = render_markdown(
        results,
        autoflip_outputs_dir=autoflip_dir,
        clipai_invocation=(
            "stub (dry_run=True)" if args.dry_run
            else f"real (cache={extraction_cache_dir})"
        ),
    )
    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text(md_body)
    logger.info("wrote markdown rollup to %s", args.output)

    # Emit JSON dump
    payload = {
        "schema": "week3_real_content_results/1",
        "manifest_path": str(manifest_path),
        "autoflip_outputs_dir": str(autoflip_dir),
        "filter": args.filter,
        "filter_slugs": (
            sorted(slug_whitelist) if slug_whitelist is not None else None
        ),
        "results": [
            {
                "slug": r.slug,
                "content_type": r.content_type,
                "target_clipcontenttype": r.target_clipcontenttype,
                "subtype": r.subtype,
                "autoflip": r.autoflip,
                "autoflip_tool": r.autoflip_tool,
                "clipai": r.clipai,
                "ground_truth": r.ground_truth,
                "verdicts": r.verdicts,
                "notes": r.notes,
                "critic": r.critic,
            }
            for r in results
        ],
    }
    Path(args.json_out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.json_out).write_text(json.dumps(payload, indent=2))
    logger.info("wrote JSON dump to %s", args.json_out)

    return 0


if __name__ == "__main__":
    sys.exit(main())
